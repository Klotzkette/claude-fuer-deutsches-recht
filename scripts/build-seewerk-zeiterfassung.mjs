#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { loadWorkbookRuntime } from './akten-workbook-runtime.mjs';

const { Workbook, SpreadsheetFile, requireRuntime } = await loadWorkbookRuntime(['jszip', 'xml-js']);
const JSZip = requireRuntime('jszip');
const xml = requireRuntime('xml-js');
const destination = process.argv[2];
if (!destination) throw new Error('Aktenordner fehlt');
const source = JSON.parse(await fs.readFile(new URL('./data/seewerk-kern.json', import.meta.url), 'utf8'));
const rows = source.blocks[98].rows;
const wb = Workbook.create();
const sheet = wb.worksheets.add('Zeiterfassung');
sheet.showGridLines = false;
sheet.getRange('A1:D13').format = { font: { name: 'Arial', size: 11, color: '#1D292F' }, rowHeight: 28, verticalAlignment: 'center', horizontalAlignment: 'left' };
[210, 100, 100, 470].forEach((width, index) => { sheet.getRangeByIndexes(0,index,13,1).format.columnWidthPx = width; });
sheet.getRange('A1:D1').merge();
sheet.getRange('A1').values = [['Seewerk Präzisionsguss GmbH']];
sheet.getRange('A1').format.font = { name: 'Arial', size: 16, bold: true };
sheet.getRange('A1:D1').format.rowHeight = 34;
sheet.getRange('A2:D3').merge();
sheet.getRange('A2').values = [[source.blocks[97].text]];
sheet.getRange('A2:D3').format.wrapText = true;
sheet.getRange('A5:D10').values = rows;
sheet.getRange('A5:D5').format = { fill: '#344D56', font: { name: 'Arial', size: 11, bold: true, color: '#FFFFFF' }, rowHeight: 30 };
sheet.getRange('A6:D10').format.rowHeight = 43;
sheet.getRange('D6:D10').format.wrapText = true;
sheet.getRange('B6:C10').setNumberFormat('@');
sheet.getRange('A5:D10').format.borders = { insideHorizontal: { style: 'thin', color: '#D4DDE0' } };
sheet.getRange('A12:D12').merge();
sheet.getRange('A12').values = [['Ausdruck vom 22.10.2026, Personalabteilung']];
sheet.getRange('A12').format.font = { name: 'Arial', size: 10, color: '#526068' };
sheet.freezePanes.freezeRows(5);
wb.recalculate();
assert.deepEqual(sheet.getRange('A5:D10').values, rows);
const qa = await fs.mkdtemp(path.join(os.tmpdir(), 'seewerk-tabelle-'));
const preview = await wb.render({ sheetName: 'Zeiterfassung', range: 'A1:D13', scale: 1.5, format: 'png' });
await fs.writeFile(path.join(qa, 'Zeiterfassung.png'), new Uint8Array(await preview.arrayBuffer()));
const inspection = await wb.inspect({ kind: 'region', sheetId: 'Zeiterfassung', range: 'A5:D10', maxChars: 3500, tableMaxRows: 6, tableMaxCols: 4 });
await fs.writeFile(path.join(qa, 'Zellwerte.ndjson'), inspection.ndjson);
const staged = path.join(qa, 'Zeiterfassung.xlsx');
await (await SpreadsheetFile.exportXlsx(wb)).save(staged);
// Nur Druckformat ergänzen; sämtliche Zellen und Gestaltung stammen aus dem Tabellenwerkzeug.
const zip = await JSZip.loadAsync(await fs.readFile(staged));
const local = element => element.name?.split(':').at(-1);
const element = (name, attributes, elements=[]) => ({ type:'element', name, attributes, elements });
const model = xml.xml2js(await zip.file('xl/worksheets/sheet1.xml').async('string'), { compact:false });
const root = model.elements.find(value => local(value)==='worksheet');
const prefix = root.name.includes(':') ? root.name.split(':')[0]+':' : '';
root.elements = root.elements.filter(value => !['pageMargins','pageSetup'].includes(local(value)));
root.elements.push(element(prefix+'pageMargins', { left:'.3',right:'.3',top:'.4',bottom:'.4',header:'.15',footer:'.15' }));
root.elements.push(element(prefix+'pageSetup', { paperSize:'9',orientation:'landscape',fitToWidth:'1',fitToHeight:'1' }));
zip.file('xl/worksheets/sheet1.xml', xml.js2xml(model, { compact:false }));
await fs.writeFile(path.join(destination, 'K10_Zeiterfassung.xlsx'), await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE'}));
console.log(`Zeiterfassung: fünf Originaldatenzeilen unverändert; Vorschau ${qa}`);
